#!/usr/bin/env python3
"""changelog_recent.py — Phase 0.8 of FLEET_FREEZE_2026-09-16.md.

CHANGELOG.md is ~620 KB and every scheduled run reads it in full (enterprise-map step 1). This
writes CHANGELOG_RECENT.md = the header + every dated section from the last WINDOW_DAYS, so a run
can read the recent slice instead. Purely derived; never edit CHANGELOG_RECENT.md by hand.
Invoked (detached) from field_scorecard_run.sh every 30 min. Idempotent; atomic write.
"""
import datetime as dt
import os
import re

OS_DIR = os.path.join(os.path.expanduser("~"), "Documents/Claude/Projects/Valley Pawn OS")
SRC = os.path.join(OS_DIR, "CHANGELOG.md")
DST = os.path.join(OS_DIR, "CHANGELOG_RECENT.md")
WINDOW_DAYS = 10   # measured 2026-09-16: 30d=440 KB, 14d=255 KB, 10d=154 KB, 7d=50 KB of a 623 KB file
HEAD_RE = re.compile(r"^## (\d{4}-\d{2}-\d{2})")


def main():
    text = open(SRC, encoding="utf-8", errors="replace").read()
    cutoff = (dt.date.today() - dt.timedelta(days=WINDOW_DAYS)).isoformat()
    lines = text.splitlines()
    out, keep, header_done = [], True, False
    kept_sections = dropped = 0
    for line in lines:
        m = HEAD_RE.match(line)
        if m:
            header_done = True
            keep = m.group(1) >= cutoff
            if keep:
                kept_sections += 1
            else:
                dropped += 1
        if not header_done or keep:
            out.append(line)
    banner = ("<!-- AUTO-GENERATED by bin/changelog_recent.py — last %d days of CHANGELOG.md "
              "(%d sections kept, %d older sections omitted). Read THIS in scheduled runs; open the "
              "full CHANGELOG.md only when you need history older than %s. Regenerated: %s -->\n\n"
              % (WINDOW_DAYS, kept_sections, dropped, cutoff, dt.datetime.now().strftime("%Y-%m-%d %H:%M")))
    body = banner + "\n".join(out).rstrip() + "\n"
    old = open(DST, encoding="utf-8").read() if os.path.exists(DST) else ""
    # skip the write if nothing but the timestamp changed (keeps mtime meaningful for git/backup)
    strip = lambda s: re.sub(r"Regenerated: [^-]*-->", "", s)
    if strip(old) == strip(body):
        return
    tmp = DST + ".tmp"
    open(tmp, "w", encoding="utf-8").write(body)
    os.replace(tmp, DST)


if __name__ == "__main__":
    main()
