#!/usr/bin/env python3
"""Render the employee-facing bonus policy + the handbook section from bonus_rules.json.

The rules file is the single source of truth. Never hand-edit the generated files —
change bonus_rules.json and re-render, so the policy, the handbook and the math can
never drift apart again (they had three different rule sets as of 2026-09-06).

Usage: python3 bin/render_policy.py [--month YYYY-MM]   (default: current regime)
Writes: BONUS_POLICY_<regime effective_from>.md and HANDBOOK_01.08_<regime>.md
"""
import json, os, sys, datetime as dt

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
R = json.load(open(os.path.join(ROOT, 'bonus_rules.json')))
month = sys.argv[sys.argv.index('--month') + 1] if '--month' in sys.argv else dt.date.today().strftime('%Y-%m')
reg = next(r for r in R['regimes'] if r['effective_from'] <= month)
q = reg['task_qualifiers']
m, a = reg['rates']['manager'], reg['rates']['associate']
pct = lambda v: f"{v*100:g}%"

goals = [f"- **Google reviews** — at least **{q['reviews_min']} new reviews** for the store that month. Ask for the review, use the signs.",
         f"- **Email capture** — at least **{q['email_pct_min']*100:g}%** of customers leave an email address. Ask for the email every time.",
         f"- **Gold scrap** — at least **{q['gold_dwt_min']:g} dwt** collected, in buckets closed during the month. Ask for the gold."]
if q.get('fb_follower_gain_min'):
    goals.append(f"- **Facebook followers** — at least **+{q['fb_follower_gain_min']} net new followers** on the store's page that month. Ask for the follow, use the signs.")
if q.get('revenue_yoy_required'):
    goals.append("- **Beat last year** — the store's revenue for the month must be above the same month last year.")

policy = f"""# Valley Pawn — Build Your Own Bonus Program
**Full Circle Finance Inc DBA Valley Pawn** · in effect for earning months from **{reg['effective_from']}** onward
_Generated from bonus_rules.json on {dt.date.today()}. Do not edit this file by hand._

## How you earn

Every month each store gets a **revenue goal**. Your bonus starts with that goal.

**1. The store has to hit its monthly revenue goal.** If the store misses its goal, there is no bonus
that month for anyone at that store — no partial, no exception. If the store hits it, everyone at
that store is in the money.

**2. Then the store's task goals decide your rate.** Hit all of them and your rate goes up; miss any
one of them and your rate goes down. Same swing either way.

| | Store hit its revenue goal **and** all task goals | Store hit its revenue goal, **missed** a task goal | Store missed its revenue goal |
|---|---|---|---|
| **Manager** | {pct(m['hit'])} of store revenue | {pct(m['miss'])} of store revenue | $0 |
| **Sales & Loan Associate / Representative** | {pct(a['hit'])} of the gross profit on your own sales | {pct(a['miss'])} of the gross profit on your own sales | $0 |

## The task goals

{chr(10).join(goals)}

## Store of the Month

**${reg['top_store_pool']:,.0f}**, split among the employees of the one store that wins the most
categories that month ({', '.join(['Email %', 'Gold dwt', 'Reviews'] + (['Facebook follower gain'] if q.get('fb_follower_gain_min') else []))}).
Ties go to the store with the most gold. The store still has to have hit its revenue goal.

## The rules that decide who gets paid

- A manager must have run the store for the **full month** to be paid on the manager rate.
- You must be **employed on the day the bonus is paid**, not just the month you earned it.
- Bonus is **paid monthly, on the first Friday after the 15th** of the following month.
- Bonus is paid at the sole discretion of management and may be changed at any time.

## Where the numbers come from

Revenue is Bravo's Net Revenue for the store — pawn service charges (interest and fees) plus the
gross profit on sales. Gross profit on your own sales comes from your Bravo employee activity.
Reviews come from Chekkit, gold from the scrap buckets closed that month, emails from the customer
records entered at the counter, Facebook from Publer. Every number is pulled from those systems the
same way every month; nobody types a figure in by hand.
"""

handbook = f"""### 01.08 Monthly Bonus Program
_Generated from bonus_rules.json on {dt.date.today()} — effective for earning months from {reg['effective_from']}. Supersedes all earlier versions of this section, including the 2.5%/50% and $3,000-minimum language carried over from the legacy manual._

Store employees earn a monthly incentive bonus, paid once a month on the Friday after the 15th.

- **Store revenue goal (hard gate).** If the store does not hit its monthly revenue goal, no bonus is
  paid to anyone at that store for that month.
- **Manager bonus:** {pct(m['hit'])} of store revenue when the store hits its revenue goal and all task goals;
  {pct(m['miss'])} when it hits the revenue goal but misses a task goal.
- **Sales & Loan Associate / Representative bonus:** {pct(a['hit'])} of the gross profit on their own sales when
  the store hits its revenue goal and all task goals; {pct(a['miss'])} when it hits the revenue goal but misses a
  task goal.
- **Task goals:** {'; '.join([g.split('** — ')[0].replace('- **', '') + ' ' + g.split('** — ')[1].split('.')[0] for g in goals])}.
- **Store of the Month:** ${reg['top_store_pool']:,.0f} split among the employees of the store winning the most
  categories, tie broken by gold weight.
- **Eligibility:** a manager must have managed the branch for the full month; all employees must be
  employed at the time of payout, not merely when the bonus was earned. Bonus pay is subject to
  supervisor discretion and may be reduced or changed, including for delinquencies beyond standard or
  breach of company policy. The company may modify the program at any time.
"""

pp = os.path.join(ROOT, f"BONUS_POLICY_{reg['effective_from']}.md")
hp = os.path.join(ROOT, f"HANDBOOK_01.08_{reg['effective_from']}.md")
open(pp, 'w').write(policy)
open(hp, 'w').write(handbook)
print('wrote', pp, 'and', hp)
